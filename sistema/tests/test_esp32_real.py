"""Pruebas de red con el ESP32 REAL (esp32_01) — sin energizar nada.
La potencia está deshabilitada: los riegos deben ser RECHAZADOS por el ESP32."""
import json, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import test_integracion as T
T.BASE = "huerto/casa/esp32_01"
b = T.Bus()
st = b.wait_for("esp32_01/state", lambda j: True, 0, 3)
T.check("ESP32 real publica estado (retenido) con firmware riego-2.0.0", st and st.get("fw") == "riego-2.0.0", str(st)[:120])
T.check("Salidas de potencia deshabilitadas y modo MANUAL al arrancar", st and st.get("power_outputs") is False and st.get("mode") == "MANUAL", "")
t0 = time.time()
tel = b.wait_for("esp32_01/telemetry", lambda j: True, t0, 15)
T.check("Telemetría real cada 10 s con hora NTP válida", tel and tel.get("ts") and tel["ts"] > 1.7e9, str(tel)[:150])
T.check("Sensores sin conectar se reportan como inválidos (no se inventan datos)", tel and not tel["soil"]["valid"] and not tel["env"]["valid"], "")
a, _ = b.cmd({"cmd": "GET_STATUS"})
T.check("GET_STATUS -> ACK OK", a and a["status"] == "OK", str(a))
a, _ = b.cmd({"cmd": "START_MANUAL", "liters": 0.5})
T.check("START_MANUAL con potencia deshabilitada -> REJECTED (seguridad)", a and a["status"] == "REJECTED", str(a))
a, _ = b.cmd({"cmd": "SET_MODE", "mode": "AUTOMATICO"})
T.check("SET_MODE AUTOMATICO -> OK (decide, no riega)", a and a["status"] == "OK" and a.get("mode_applied") == "AUTOMATICO", str(a))
a, _ = b.cmd({"cmd": "SET_MODE", "mode": "MANUAL"})
T.check("SET_MODE MANUAL -> OK", a and a["status"] == "OK", str(a))
a, _ = b.cmd({"cmd": "APPLY_CONFIG", "version": 1, "params": {"hum_min": 40}})
T.check("APPLY_CONFIG inválido -> REJECTED en el ESP32", a and a["status"] == "REJECTED", str(a))
a, cid = b.cmd({"cmd": "GET_IA"})
a2, _ = b.cmd({"cmd": "GET_IA", "id": cid})
T.check("Duplicado -> DUPLICATE en el ESP32", a2 and a2["status"] == "DUPLICATE", str(a2))
a, _ = b.cmd({"cmd": "GET_STATUS", "ts": int(time.time()) - 900})
T.check("Comando viejo -> STALE en el ESP32 (hora NTP)", a and a["status"] == "STALE", str(a))
t0 = time.time()
a, _ = b.cmd({"cmd": "NET_DIAG"})
d = b.wait_for("esp32_01/diag", lambda j: True, t0, 8)
T.check("Diagnóstico de red sin contraseñas", d and d["wifi"]["connected"] and "pass" not in json.dumps(d).lower(), str(d)[:160] if d else "")
w = b.wait_for("esp32_01/weather", lambda j: True, 0, 2)
T.check("Open-Meteo desde el ESP32 por HTTPS (vigente)", w and w.get("valid") and w.get("fresh"), str(w)[:150])
ia = b.wait_for("esp32_01/ia", lambda j: True, 0, 2)
T.check("IA del ESP32 real en APRENDIZAJE (sin datos: no se llama entrenada)", ia and ia.get("status") == "APRENDIZAJE", "")
time.sleep(3)
rows = T.q("SELECT COUNT(*) FROM readings WHERE device='esp32_01' AND simulated=0")
T.check("Node-RED guarda la telemetría REAL en SQLite (simulated=0)", rows[0][0] > 0, str(rows))
ok = sum(1 for r in T.RES if r[1])
fn = os.path.join(T.ROOT, "tests", "resultados", "esp32_real_%s.txt" % time.strftime("%Y%m%d_%H%M"))
with open(fn, "w", encoding="utf-8") as f:
    f.write("PRUEBAS CON EL ESP32 REAL esp32_01 (COM8, Wi-Fi RED_DE_CASA_2.4) %s\n" % time.strftime("%Y-%m-%d %H:%M"))
    for n, g, dd in T.RES:
        f.write("[%s] %s %s\n" % ("PASS" if g else "FAIL", n, "" if g else dd))
    f.write("RESULTADO: %d PASS, %d FAIL\n" % (ok, len(T.RES) - ok))
print("RESULTADO: %d PASS, %d FAIL -> %s" % (ok, len(T.RES) - ok, fn))
